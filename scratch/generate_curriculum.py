def escape_dart(s):
    if s is None:
        return 'null'
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"

def format_list(lst):
    return '[' + ', '.join(escape_dart(x) for x in lst) + ']'

